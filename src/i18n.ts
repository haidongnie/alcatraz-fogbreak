const dict: Record<Lang, Record<string, string>> = { zh, en };

function applyDocumentLang() {
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
}

/** Picks the language (?lang= override, saved choice, else browser language) and returns it. */
export function initI18n(): Lang {
  let pick: string | null = new URLSearchParams(location.search).get('lang');
  if (pick !== 'zh' && pick !== 'en') {
    try { pick = localStorage.getItem(LANG_KEY); } catch { pick = null; }
  }
  if (pick === 'zh' || pick === 'en') current = pick;
  else {
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
    current = langs.some((l) => l?.toLowerCase().startsWith('zh')) ? 'zh' : 'en';
  }
  applyDocumentLang();
  return current;
}
export function getLang(): Lang { return current; }
/** Switches language, remembers it and notifies `onLangChange` listeners (the UI re-labels itself). */
export function setLang(l: Lang) {
  if (l === current) return;
  current = l;
  try { localStorage.setItem(LANG_KEY, l); } catch { /* private mode */ }
  applyDocumentLang();
  for (const fn of listeners) fn(l);
}
export function onLangChange(fn: (l: Lang) => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}
/** True when the key exists (in any language). */
export function hasKey(key: string): boolean {
  return key in dict.zh || key in dict.en;
}
/** Translate a key; `{name}` placeholders are replaced from args. Unknown keys return the key. */
export function t(key: string, args?: Record<string, string | number>): string {
  let s = dict[current][key] ?? dict.en[key] ?? key;
  if (args) for (const [k, v] of Object.entries(args)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
